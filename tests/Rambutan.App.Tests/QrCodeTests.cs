    public static TheoryData<int> Cases() => [.. Enumerable.Range(0, Vectors.Length)];

    [Theory]
    [MemberData(nameof(Cases))]
    public void MatchesTheReferenceEncoder(int index)
    {
        var expected = Vectors[index];

        var code = QrCode.Encode(expected.Text);

        Assert.Equal(expected.Version, code.Version);
        Assert.Equal(expected.Mask, code.Mask);
        Assert.Equal(expected.Rows.Length, code.Size);
        var rows = Enumerable.Range(0, code.Size)
            .Select(y => string.Concat(Enumerable.Range(0, code.Size).Select(x => code[x, y] ? '1' : '0')))
            .ToArray();
        Assert.Equal(expected.Rows, rows);
    }

    [Fact]
    public void TextTooLongForVersion10_IsRefused()
    {
        Assert.Throws<ArgumentException>(() => QrCode.Encode(new string('x', 214)));
        Assert.Equal(QrCode.MaxVersion, QrCode.Encode(new string('x', 213)).Version);
    }
